/**
 * Copie un texte. À appeler directement dans un gestionnaire d'événement
 * utilisateur (exigence d'iOS). Repli sur execCommand quand l'API
 * Clipboard est absente (page non sécurisée, ex. serveur de dev en HTTP).
 */
export async function copyText(text: string): Promise<boolean> {
  try {
    if (navigator.clipboard && window.isSecureContext) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    // on tente le repli
  }
  try {
    const ta = document.createElement('textarea');
    ta.value = text;
    ta.setAttribute('readonly', '');
    ta.style.position = 'fixed';
    ta.style.opacity = '0';
    ta.style.fontSize = '16px'; // évite le zoom iOS
    document.body.appendChild(ta);
    ta.select();
    ta.setSelectionRange(0, text.length);
    const ok = document.execCommand('copy');
    ta.remove();
    return ok;
  } catch {
    return false;
  }
}
